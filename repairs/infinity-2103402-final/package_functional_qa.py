#!/usr/bin/env python3
"""Build an isolated UI-only 2103402 QA candidate from exact signed 2103401.

Never changes native engine/DEX, profiles, provider routes, Cobra, or the
accepted source artifact. The only APK member mutations are the exact 19
authorized stage overlays, two addon.xml versions and manifest versionCode.
Android signature files are regenerated by apksigner on the runner.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
import shutil
import struct
import sys
from pathlib import Path
from zipfile import ZipFile

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from audit_staging import audit

PREV_CODE = 2103401
NEW_CODE = 2103402
NATIVE_NAME = "lib/arm64-v8a/libkodi.so"
VERSIONS = {
    "script.infinity.commandcenter/addon.xml": (b'version="0.3.5.35"', b'version="0.3.5.36"'),
    "skin.infinity.diggz/addon.xml": (b'version="1.0.5.242"', b'version="1.0.5.243"'),
}
COMPONENTS = {
    "script.infinity.commandcenter": ("script.infinity.commandcenter-0.3.5.35.zip", "script.infinity.commandcenter-0.3.5.36.zip"),
    "script.infinity.uirepair": ("script.infinity.uirepair-0.1.18.zip", "script.infinity.uirepair-0.1.18.zip"),
    "script.infinity.watchedbridge": ("script.infinity.watchedbridge-1.0.16.zip", "script.infinity.watchedbridge-1.0.16.zip"),
    "skin.infinity.diggz": ("skin.infinity.diggz-1.0.5.242.zip", "skin.infinity.diggz-1.0.5.243.zip"),
}
SIG_MEMBERS = {"META-INF/INFINITY.SF", "META-INF/INFINITY.RSA", "META-INF/MANIFEST.MF"}
BASE_APK = "Infinity-2103401-Universal-Performance-QA.apk"
QA_APK = "Infinity-2103402-Functional-Corrective-QA.apk"


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def bump_version(member: str, data: bytes) -> bytes:
    old, new = VERSIONS[member]
    if data.count(old) != 1 or new in data:
        raise ValueError("Unexpected version preimage: " + member)
    value = data.replace(old, new, 1)
    assert value.replace(new, old, 1) == data
    return value


def manifest_code(data: bytes) -> bytes:
    # AXML root typed android:versionCode value: type=integer, original value.
    prefix = bytes.fromhex("ffffffff08000010")
    old, new = prefix + struct.pack("<I", PREV_CODE), prefix + struct.pack("<I", NEW_CODE)
    if data.count(old) != 1 or data.count(new):
        raise ValueError("Manifest versionCode is not the exact protected source")
    result = data.replace(old, new, 1)
    if result.replace(new, old, 1) != data:
        raise ValueError("Manifest member changed outside versionCode")
    return result


def write_zip(source: ZipFile, output: Path, edits: dict[str, bytes], skip=frozenset()):
    names = source.namelist()
    if len(names) != len(set(names)):
        raise ValueError("Duplicate entries in source ZIP")
    if not set(edits).issubset(names):
        raise ValueError("Missing exact original member: " + repr(set(edits) - set(names)))
    output.parent.mkdir(parents=True, exist_ok=True)
    with ZipFile(output, "w", allowZip64=True) as target:
        for info in source.infolist():
            if info.filename in skip:
                continue
            # Retain every unowned member's content and original compression.
            with target.open(copy.copy(info), "w", force_zip64=info.file_size >= 2**31) as dest:
                if info.filename in edits:
                    dest.write(edits[info.filename])
                else:
                    with source.open(info, "r") as original:
                        shutil.copyfileobj(original, dest, length=1024 * 1024)


def verify_member_deltas(baseline: Path, candidate: Path, edits: dict[str, bytes], unsigned=False):
    with ZipFile(baseline) as before, ZipFile(candidate) as after:
        first, second = set(before.namelist()), set(after.namelist())
        assert len(before.namelist()) == len(first) and len(after.namelist()) == len(second)
        removed = first - second
        added = second - first
        if unsigned:
            assert removed == SIG_MEMBERS and not added, (removed, added)
        else:
            # Newly generated signature files are expected, but no app assets
            # or native files may be removed or introduced.
            assert not {n for n in removed | added if not n.startswith("META-INF/")}, (removed, added)
        changed = []
        for entry in sorted(first & second):
            if entry in SIG_MEMBERS:
                continue
            old_info, new_info = before.getinfo(entry), after.getinfo(entry)
            if old_info.CRC == new_info.CRC and old_info.file_size == new_info.file_size:
                # CRC and size gate is cheap; every potentially edited member
                # is independently verified using SHA256 below.
                if entry in edits and after.read(entry) != edits[entry]:
                    raise ValueError("Candidate edited member mismatch: " + entry)
                continue
            old, new = before.read(entry), after.read(entry)
            if entry not in edits or new != edits[entry]:
                raise ValueError("Unexpected APK member change: " + entry)
            changed.append(entry)
        if set(changed) != set(edits):
            raise ValueError("Expected authorized changes absent: " + repr(set(edits) - set(changed)))
        for name in edits:
            assert after.read(name) == edits[name], name
        for member in (NATIVE_NAME, "classes.dex"):
            with before.open(member) as a, after.open(member) as b:
                ah, bh = hashlib.sha256(), hashlib.sha256()
                for source, h in [(a, ah), (b, bh)]:
                    for chunk in iter(lambda: source.read(1024 * 1024), b""):
                        h.update(chunk)
                if ah.digest() != bh.digest():
                    raise ValueError("Protected native/DEX binary changed: " + member)
    return sorted(changed)


def make_edits(apk: Path, overlay: Path):
    stage = audit(apk, overlay)
    if stage["status"] != "PASS" or len(stage["members"]) != 19:
        raise ValueError("Staged source not entirely verified")
    edits = {"assets/addons/" + n: (overlay / n).read_bytes()
             for n in stage["members"]}
    with ZipFile(apk) as z:
        edits["AndroidManifest.xml"] = manifest_code(z.read("AndroidManifest.xml"))
        for n in VERSIONS:
            edits["assets/addons/" + n] = bump_version(n, z.read("assets/addons/" + n))
    if len(edits) != 22:
        raise ValueError("Unexpected QA change set size")
    if any("cobra" in name.casefold() for name in edits):
        raise ValueError("Cobra member in allowed set")
    return edits, stage


def make(args):
    baseline = args.baseline / BASE_APK
    if not baseline.is_file():
        raise FileNotFoundError(baseline)
    edits, stage = make_edits(baseline, args.overlay)
    unsigned = args.out / "unsigned-2103402.apk"
    with ZipFile(baseline) as original:
        write_zip(original, unsigned, edits, SIG_MEMBERS)
    altered = verify_member_deltas(baseline, unsigned, edits, unsigned=True)
    for addon, (source_name, out_name) in COMPONENTS.items():
        selected = {n[len("assets/addons/"):] : blob for n, blob in edits.items()
                    if n.startswith("assets/addons/" + addon + "/")}
        source_file = args.baseline / source_name
        destination = args.out / out_name
        if not selected:
            shutil.copyfile(source_file, destination)
        else:
            with ZipFile(source_file) as original:
                write_zip(original, destination, selected)
                with ZipFile(destination) as packed:
                    for n, v in selected.items():
                        if packed.read(n) != v:
                            raise ValueError("Component ZIP member mismatch: " + n)
    (args.out / "QA-STAGE-RECEIPT.json").write_text(json.dumps({
        "source_build": 40089463702,
        "protected_baseline_sha256": digest(baseline.read_bytes()),
        "qa_version_code": NEW_CODE,
        "native_engine": "UNCHANGED",
        "dex": "UNCHANGED",
        "cobra": "UNCHANGED",
        "staged_host_verified": sorted(stage["members"]),
        "additional_addon_version_bumps": sorted(VERSIONS),
        "expected_apk_member_delta": altered,
        "search_sigbus": "UNRESOLVED: original fault stack absent",
        "home_post_playback_45s_delay": "NOT VERIFIED FIXED",
        "provider_chooser": "NOT FIXED",
        "information_focus_return": "NOT VERIFIED FIXED",
        "health_native_diagnostics": "EXCLUDED FROM THIS QA",
        "physical_fold": "NOT TESTED",
        "acceptance": "INTERNAL QA ONLY - INSTALL OVER FOR USER VALIDATION"
    }, indent=2) + "\n")
    print("QA stage prepared with exact approved 22-member delta")


def verify(args):
    baseline = args.baseline / BASE_APK
    edits, _ = make_edits(baseline, args.overlay)
    changed = verify_member_deltas(baseline, args.signed, edits, unsigned=False)
    if len(changed) != 22:
        raise ValueError("Signed APK missing approved changes")
    print("Signed APK content guard PASSED: exact 22-member delta, native and DEX protected")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("action", choices=["make", "verify"])
    parser.add_argument("--baseline", type=Path, required=True)
    parser.add_argument("--overlay", type=Path, default=HERE / "overlay")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--signed", type=Path)
    args = parser.parse_args()
    if args.action == "make":
        if args.out is None:
            parser.error("--out required for make")
        make(args)
    else:
        if args.signed is None:
            parser.error("--signed required for verify")
        verify(args)
