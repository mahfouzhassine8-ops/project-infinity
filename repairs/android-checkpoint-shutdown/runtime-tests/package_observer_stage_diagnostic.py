def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def load(path):
    return json.loads(Path(path).read_text())


def save(path, value):
    Path(path).write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def pinned_native():
    require(isinstance(NATIVE_RUN, int) and NATIVE_RUN > 0 and
            re.fullmatch(r'[0-9a-f]{40}', NATIVE_SOURCE) is not None,
            'Live-stage native run/source have not been pinned; packaging is disabled')


def checked_archive(path):
    archive = zipfile.ZipFile(path)
    names = archive.namelist()
    try:
        require(len(names) == len(set(names)), 'Duplicate APK entry names: ' + str(path))
        require(archive.testzip() is None, 'APK CRC failure: ' + str(path))
        require(ENGINE in names, 'ARM64 engine absent: ' + str(path))
    except Exception:
        archive.close()
        raise
    return archive


def payload_identity(parent, candidate):
    """Require exact names and all uncompressed payload bytes except one engine.

    Re-signing necessarily regenerates v1 signature contents/signing blocks.
    Signature entry names must still match; no other META-INF file is exempt.
    """
    with checked_archive(parent) as old, checked_archive(candidate) as new:
        names = set(old.namelist())
        require(names == set(new.namelist()), 'APK entry-name set changed')
        changed = sorted(name for name in names if old.read(name) != new.read(name))
        payload_changed = [name for name in changed if not SIGNATURE.fullmatch(name)]
        require(payload_changed == [ENGINE], 'Unexpected APK payload mutation: ' + repr(payload_changed))
        protected = sorted(name for name in names if name != ENGINE and not SIGNATURE.fullmatch(name))
        java = sorted(name for name in names if re.fullmatch(r'classes(?:[0-9]+)?\.dex', name))
        require(java and 'AndroidManifest.xml' in protected, 'Manifest or Java payload absent')
        return dict(changed_payload_entries=payload_changed,
                    signature_metadata_entries_regenerated=[name for name in changed if SIGNATURE.fullmatch(name)],
                    apk_entry_names_unchanged=True, protected_entry_count=len(protected),
                    all_other_uncompressed_payload_bytes_identical=True,
                    java_dex_sha256={name: hashlib.sha256(new.read(name)).hexdigest() for name in java},
                    manifest_sha256=hashlib.sha256(new.read('AndroidManifest.xml')).hexdigest(),
                    native_packaged_sha256=hashlib.sha256(new.read(ENGINE)).hexdigest())


def rewrite_engine(parent, engine, output):
    """Copy payloads as-is; only signature contents are regenerated by signing."""
    with checked_archive(parent) as old, zipfile.ZipFile(output, 'w') as new:
        for info in old.infolist():
            if SIGNATURE.fullmatch(info.filename):
                continue
            new.writestr(copy.copy(info), engine.read_bytes() if info.filename == ENGINE else old.read(info.filename))


def verify_rc05(inputs):
    root = inputs / 'essential-fold-test'
    apk = root / RC05_APK
    require(sha(apk) == RC05_APK_SHA, 'Saved RC05 APK digest mismatch')
    proof = load(root / 'ESSENTIAL-FIRST-SIGNED-TEST-PRESERVATION.json')
    require(proof['apk_sha256'] == RC05_APK_SHA and proof['file'] == RC05_APK,
            'Saved RC05 signed receipt does not identify this APK')
    require(proof['native_source_commit'] == RC05_NATIVE_SOURCE and
            proof['android_source_commit'] == RC05_SOURCE and
            proof['native_packaged_sha256'] == RC05_ENGINE_SHA,
            'Saved RC05 source/engine identity mismatch')
    require(proof['same_permanent_signer'] == SIGNER and proof['package'] == 'com.projectinfinity.kodi' and
            proof['version_code'] == 2103377 and proof['version_name'] == '1.0.9-Essential-First-TEST4-RC05',
            'Saved RC05 signing/package identity mismatch')
    require(proof['apk_deliverable'] is False and proof['final_lock_authorized'] is False and
            proof['java_regressions_verified'] is True and proof['java_producer_adapters_verified'] is True and
            proof['signed_test2_baseline_preserved'] is True and proof['signed_test3_baseline_preserved'] is True,
            'Saved RC05 acceptance/preservation contract missing')
    regression = load(root / 'JAVA-REGRESSION-VERIFICATION.json')
    for key, count in (('original_274', 274), ('new_save_cases', 26), ('completion_race_cases', 8)):
        require(regression[key] == dict(tests=count, failures=0, errors=0, skipped=0),
                'Saved Java regression failure: ' + key)
    require(regression['original_test_sources_unchanged'] is True, 'Saved original test source proof missing')
    with checked_archive(apk) as archive:
        require(hashlib.sha256(archive.read(ENGINE)).hexdigest() == RC05_ENGINE_SHA,
                'Saved RC05 embedded engine mismatch')
    return apk


def tool_output(*args):
    return subprocess.check_output([str(arg) for arg in args], text=True, stderr=subprocess.STDOUT)


def verify_android(apk, out, label):
    bt = Path(os.environ['ANDROID_HOME']) / 'build-tools/34.0.0'
    cert = tool_output(bt / 'apksigner', 'verify', '--verbose', '--print-certs', apk)
    cert_digests = re.findall(r'^signer #[0-9]+ certificate sha-256 digest: ([0-9a-f]+)\s*$', cert.lower(), re.M)
    require(cert_digests == [SIGNER], 'Wrong or multiple permanent signers: ' + label)
    for scheme in (2, 3):
        require(re.search(r'Verified using v' + str(scheme) + r' scheme[^\n]+true', cert),
                'Missing APK signature v' + str(scheme) + ': ' + label)
    tool_output(bt / 'zipalign', '-c', '-p', '4', apk)
    badging = tool_output(bt / 'aapt', 'dump', 'badging', apk)
    require("package: name='com.projectinfinity.kodi' versionCode='2103377'" in badging and
            "versionName='1.0.9-Essential-First-TEST4-RC05'" in badging,
            'Package/version changed: ' + label)
    require("application-label:'Infinity'" in badging and 'application-debuggable' not in badging,
            'Branding/debug mode changed: ' + label)
    (out / (label + '-certificate.txt')).write_text(cert)
    (out / (label + '-badging.txt')).write_text(badging)


def exports(file):
    rows = [line.split() for line in tool_output('readelf', '--dyn-syms', '--wide', file).splitlines()]
    return {row[-1].split('@')[0] for row in rows
            if len(row) >= 8 and row[4:6] == ['GLOBAL', 'DEFAULT'] and row[6] != 'UND'}


def needed(file):
    return sorted(re.findall(r'\(NEEDED\).*?\[(.*?)\]', tool_output('readelf', '-d', '-W', file)))


def tree_hashes(root):
    require(root.is_dir(), 'Installed first-party source inventory missing: ' + str(root))
    result = {str(path.relative_to(root)): sha(path) for path in root.rglob('*') if path.is_file()}
    require(result, 'Empty installed first-party inventory')
    return result


def fixture_inventory(root):
    """Match essential_android_probe's existing copytree cache exclusions.

    These host caches never enter the disposable Android fixture. APK payload
    bytes, including any caches inside the APK, remain protected independently.
    """
    all_files = tree_hashes(root)
    excluded = {name: digest for name, digest in all_files.items()
                if any(part == '__pycache__' or part.endswith('.pyc')
                       for part in Path(name).parts)}
    installed = {name: digest for name, digest in all_files.items() if name not in excluded}
    require(installed, 'Empty installed first-party source inventory after fixture exclusions')
    return dict(installed=installed, excluded_host_caches=excluded)


def verify_first_party_sources(native, inputs, evidence_path=None):
    before = fixture_inventory(inputs / 'native-evidence/installed-addons')
    after = fixture_inventory(native / 'installed-addons')
    old, new = before['installed'], after['installed']
    result = dict(fixture_copy_exclusions=['__pycache__', '*.pyc'],
                  saved_rc05=before, diagnostic_native=after,
                  added=sorted(new.keys() - old.keys()), removed=sorted(old.keys() - new.keys()),
                  changed=sorted(name for name in old.keys() & new.keys() if old[name] != new[name]),
                  installed_sources_identical=old == new)
    if evidence_path is not None:
        save(evidence_path, result)
    require(result['installed_sources_identical'],
            'Native installed first-party sources differ from saved RC05: ' +
            json.dumps({key: result[key] for key in ('added', 'removed', 'changed')}, sort_keys=True))
    return result


def verify_native(native, inputs, evidence_path=None):
    pinned_native()
    proof = load(native / 'ENGINE-PROOF.json')
    require(proof['source_commit'] == NATIVE_SOURCE and proof['complete_native_engine_compiled'] is True and
            proof['all_reviewed_inputs_preserved'] is True and proof['defined_native_entry_verified'] is True,
            'Native artifact is not the pinned complete reviewed engine')
    require(proof['shutdown_policy'] == 'essential_first_process_exit_v1' and
            proof['diagnostic_owners'] == 17 and proof['essential_owners'] == 16 and
            proof['optional_retirement_required'] is False and proof['apk_deliverable'] is False and
            proof['locked'] is False and proof['android_process_death_verified'] is False,
            'Native essential-save/diagnostic contract changed')
    binary = native / 'libkodi.so'
    require(sha(binary) == proof['native_sha256'], 'Native binary digest differs from ENGINE-PROOF')
    require(re.fullmatch(r'[0-9a-f]{64}', proof['source_manifest_sha256']), 'Native source manifest identity absent')
    data = binary.read_bytes()
    for marker in LIVE_MARKERS:
        require(marker in data, 'Live-stage binary marker missing: ' + repr(marker))
    delta = load(native / 'ESSENTIAL-FIRST-SOURCE-DELTA.json')
    require(delta['source_commit'] == NATIVE_SOURCE and delta['diagnostic_owner_count'] == 17 and
            delta['essential_owner_count'] == 16 and delta['locked'] is False and delta['apk_deliverable'] is False,
            'Native staged source delta identity mismatch')
    staged = {}
    for rel in LIVE_HEADERS:
        local = ROOT / 'repairs/essential-first-2103377/runtime' / rel
        pinned = subprocess.check_output(['git', 'show', NATIVE_SOURCE + ':' + str(local.relative_to(ROOT))], cwd=ROOT)
        require(pinned == local.read_bytes(), 'Reviewed live-stage header changed after native source pin: ' + rel)
        digest = hashlib.sha256(pinned).hexdigest()
        require(delta['after'].get(rel) == digest, 'Staged live-stage header hash mismatch: ' + rel)
        staged[rel] = digest
    inventory = verify_first_party_sources(native, inputs, evidence_path)
    return proof, staged, inventory


def package(args):
    pinned_native()
    require(not args.out.exists(), 'Refusing to reuse stale diagnostic output')
    args.out.mkdir(parents=True)
    parent = verify_rc05(args.rc05_inputs)
    verify_android(parent, args.out, 'saved-rc05')
    proof, staged, inventory = verify_native(args.native, args.rc05_inputs,
        args.out / 'FIRST-PARTY-FIXTURE-PRESERVATION.json')
    for key in ('INFINITY_KEYSTORE_B64', 'INFINITY_STORE_PASSWORD', 'INFINITY_KEY_PASSWORD', 'INFINITY_KEY_ALIAS'):
        require(bool(os.environ.get(key)), 'Permanent signing configuration missing: ' + key)
    require(os.environ.get('NDK_VER') == NDK_VERSION, 'Wrong strip toolchain version')
    ndk = Path(os.environ['ANDROID_HOME']) / 'ndk' / NDK_VERSION
    properties = (ndk / 'source.properties').read_text()
    require(re.search(r'^Pkg.Revision\s*=\s*' + re.escape(NDK_VERSION) + r'\s*$', properties, re.M),
            'Pinned NDK installation identity mismatch')
    original = args.out / 'rc05-libkodi.so'
    with checked_archive(parent) as archive:
        original.write_bytes(archive.read(ENGINE))
    engine = args.out / 'diagnostic-libkodi.so'
    shutil.copyfile(args.native / 'libkodi.so', engine)
    strip = ndk / 'toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-strip'
    subprocess.run([str(strip), '--strip-unneeded', str(engine)], check=True)
    require('AArch64' in tool_output('readelf', '-h', engine), 'Diagnostic engine is not ARM64')
    before, after = exports(original), exports(engine)
    require(not before - after, 'RC05 native exports removed: ' + repr(sorted(before - after)))
    require({n for n in before if n.startswith('Java_')} == {n for n in after if n.startswith('Java_')},
            'Java JNI native export contract changed')
    require(needed(original) == needed(engine), 'Native NEEDED dependencies changed')
    for marker in LIVE_MARKERS:
        require(marker in engine.read_bytes(), 'Stripped engine lost live-stage marker: ' + repr(marker))
    unsigned = args.out / 'internal-observer-stage-unsigned.apk'
    rewrite_engine(parent, engine, unsigned)
    signed = args.out / DIAGNOSTIC_APK
    subprocess.run(['bash', str(ROOT / 'scripts/sign-infinity71.sh'), str(unsigned), str(signed)], check=True)
    verify_android(signed, args.out, 'internal-observer-stage')
    identity = payload_identity(parent, signed)
    require(identity['native_packaged_sha256'] == sha(engine), 'Signed engine differs from verified stripped engine')
    receipt = dict(status='INTERNAL OBSERVER STAGE DIAGNOSTIC ONLY - NOT A FOLD CANDIDATE',
                   file=DIAGNOSTIC_APK, apk_sha256=sha(signed), bytes=signed.stat().st_size,
                   reused_rc05_run=RC05_RUN, reused_rc05_job=RC05_JOB, reused_rc05_source=RC05_SOURCE,
                   reused_rc05_apk_sha256=RC05_APK_SHA, reused_rc05_native_sha256=RC05_ENGINE_SHA,
                   saved_308_results_verified=True, java_payload_byte_identical=True,
                   java_rebuilt=False, java_tests_rerun=False, native_run=NATIVE_RUN, native_source=NATIVE_SOURCE,
                   native_unstripped_sha256=proof['native_sha256'], native_staged_header_sha256=staged,
                   first_party_fixture_preservation=inventory,
                   native_source_manifest_sha256=proof['source_manifest_sha256'],
                   native_exports_removed=[], native_exports_added=sorted(after-before), native_needed=needed(engine),
                   native_jni_exports_unchanged=True, permanent_signer=SIGNER, ndk_version=NDK_VERSION,
                   package='com.projectinfinity.kodi', version_code=2103377,
                   version_name='1.0.9-Essential-First-TEST4-RC05', all_16_essential_owners_preserved=True,
                   shutdown_policy='essential_first_process_exit_v1', live_initialization_markers_verified=True,
                   physical_fold_accepted=False, apk_deliverable=False, apk_promotion_authorized=False,
                   final_lock_authorized=False, **identity)
    save(args.out / REPORT, receipt)
    shutil.copyfile(args.rc05_inputs / 'essential-fold-test/JAVA-REGRESSION-VERIFICATION.json',
                    args.out / 'REUSED-RC05-JAVA-REGRESSION-VERIFICATION.json')
    (args.out / 'SHA256SUMS').write_text(receipt['apk_sha256'] + '  ' + signed.name + '\n')
    # Keep evidence small and avoid publishing unsigned or intermediate engines.
    for path in (unsigned, original, engine):
        path.unlink()
    print('PASS: internal diagnostic signed; every non-engine payload byte and all entry names match RC05.')


def verify(args):
    pinned_native()
    parent = verify_rc05(args.rc05_inputs)
    report = load(args.out / REPORT)
    signed = args.out / DIAGNOSTIC_APK
    require(report['file'] == DIAGNOSTIC_APK and report['apk_sha256'] == sha(signed), 'Diagnostic APK/receipt mismatch')
    require(report['native_run'] == NATIVE_RUN and report['native_source'] == NATIVE_SOURCE and
            report['reused_rc05_apk_sha256'] == RC05_APK_SHA and report['saved_308_results_verified'] is True,
            'Diagnostic source or reused Java identity mismatch')
    require(report['apk_deliverable'] is False and report['apk_promotion_authorized'] is False and
            report['final_lock_authorized'] is False and report['physical_fold_accepted'] is False,
            'Internal-only diagnostic restriction missing')
    identity = payload_identity(parent, signed)
    for key, value in identity.items():
        require(report.get(key) == value, 'Diagnostic payload proof mismatch: ' + key)
    require(load(args.out / 'REUSED-RC05-JAVA-REGRESSION-VERIFICATION.json') ==
            load(args.rc05_inputs / 'essential-fold-test/JAVA-REGRESSION-VERIFICATION.json'),
            'Copied saved Java proof changed')
    inventory = load(args.out / 'FIRST-PARTY-FIXTURE-PRESERVATION.json')
    require(report['first_party_fixture_preservation'] == inventory and
            inventory['saved_rc05'] == fixture_inventory(args.rc05_inputs / 'native-evidence/installed-addons') and
            inventory['installed_sources_identical'] is True and
            inventory['diagnostic_native']['installed'] == inventory['saved_rc05']['installed'],
            'First-party fixture preservation proof changed')
    verify_android(parent, args.out, 'saved-rc05-recheck')
    verify_android(signed, args.out, 'internal-observer-stage-recheck')
    print('PASS: exact internally signed diagnostic payload independently rechecked; no promotion authority.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('mode', choices=('package', 'verify'))
    parser.add_argument('--rc05-inputs', type=Path, required=True)
    parser.add_argument('--native', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    if args.mode == 'package':
        require(args.native is not None, 'Pinned native evidence required')
        package(args)
    else:
        verify(args)
