"""Continue from exact signed2103426; compile genuine Infinity-only inputs."""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess
import sys
from zipfile import ZipFile

HERE = Path(__file__).resolve().parent
TASK = HERE.parent
REPO = TASK.parents[1]
sys.path.insert(0, str(TASK))
from stage import preserved_functions
sys.path.insert(0, str(REPO / 'repairs/infinity-final-closure-2103407'))
import module_bundle
from rail_isolation import home, includes

CC = 'script.infinity.commandcenter'
SKIN = 'skin.infinity.diggz'
PREFIX = 'assets/addons/'
sha = lambda raw: hashlib.sha256(raw).hexdigest()


def save(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True) + '\n')


def generate(baseline, out):
    scope = json.loads((HERE / 'SCOPE.json').read_text())
    authority = json.loads(subprocess.check_output(['git', '-C', str(REPO), 'show',
        scope['input_apk_source'] + ':repairs/dual-experience-isolation-2103420/release-authority.json']))
    with baseline.open('rb') as stream:
        assert hashlib.file_digest(stream, 'sha256').hexdigest() == scope['input_apk_sha256']
    assert not out.exists(), 'Fresh staging directory required'
    out.mkdir(parents=True)
    candidate = out / 'candidate-addons'
    changes, old_files = {}, {}
    with ZipFile(baseline) as archive:
        for name in archive.namelist():
            if not name.startswith(PREFIX): continue
            rel = name[len(PREFIX):]
            if rel.split('/')[0] in module_bundle.IDS:
                target = candidate / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(archive.read(name))
        old_manifest, original = module_bundle.build(candidate)
        assert old_manifest == (candidate / CC / module_bundle.MANIFEST).read_bytes()
        subprocess.run(['openssl', 'dgst', '-sha256', '-verify',
            str(REPO / 'repairs/infinity-final-closure-2103407/ORIGINAL-INFINITY-PUBLIC-KEY.pem'),
            '-signature', str(candidate / CC / (module_bundle.MANIFEST + '.sig')),
            str(candidate / CC / module_bundle.MANIFEST)], check=True, capture_output=True)
        shutil.copytree(candidate, out / 'input-addons')
        functions = {}
        allowed = {'resume_hub.py': {'progress_shows', 'next_episodes', 'entries', '_entries_projection', 'counts'},
                   'plugin.py': {'_values_for', 'listing'},
                   'skin_upgrade.py': {'_content_path_var', '_patch_home'}}
        for path in sorted((HERE / 'overlay' / CC).iterdir()):
            rel = CC + '/' + path.name
            before, after = original[rel], path.read_bytes()
            assert before != after
            if path.suffix == '.py':
                functions[rel] = preserved_functions(before, after, allowed[path.name])
            else:
                assert path.name == 'addon.xml'
                assert before.replace(b'version="0.3.5.50"', b'version="0.3.5.51"', 1) == after
            (candidate / rel).write_bytes(after)
            changes[PREFIX + rel] = after
        for leaf in (module_bundle.MANIFEST, module_bundle.MANIFEST + '.sig'):
            (candidate / CC / leaf).unlink()
        module = module_bundle.prepare(candidate)
        new_manifest, revised = module_bundle.build(candidate)
        assert set(original) == set(revised)
        assert {n for n in original if original[n] != revised[n]} == {
            n[len(PREFIX):] for n in changes}
        changes[PREFIX + CC + '/' + module_bundle.MANIFEST] = new_manifest
        # Skin files remain Infinity owned. No player, settings, providers or
        # shared/native files are regenerated by this transformation.
        skin = {n[len(PREFIX + SKIN + '/'):]: archive.read(n) for n in archive.namelist()
                if n.startswith(PREFIX + SKIN + '/')}
        for name, raw in skin.items():
            if name.endswith(('/Home.xml', '/Includes_InfinityHomeUnified.xml')):
                target = out / 'input-addons' / SKIN / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(raw)
        for name, raw in skin.items():
            if name.endswith('/Home.xml'):
                changes[PREFIX + SKIN + '/' + name] = home(raw)
            elif name.endswith('/Includes_InfinityHomeUnified.xml'):
                changes[PREFIX + SKIN + '/' + name] = includes(raw)
        addon = skin['addon.xml'].replace(b'version="1.0.5.247"', b'version="1.0.5.248"', 1)
        assert addon != skin['addon.xml']
        changes[PREFIX + SKIN + '/addon.xml'] = addon
        meta = json.loads(skin['infinity-skin.json'])
        meta.update(candidate=248, version='1.0.5.248', skin_version='1.0.5.248')
        changes[PREFIX + SKIN + '/infinity-skin.json'] = (json.dumps(meta, indent=2, sort_keys=True) + '\n').encode()
        manifest = json.loads(skin['Infinity-Protected-Manifest.json'])
        manifest.update(candidate=248, candidate_version='1.0.5.248', skin_version='1.0.5.248')
        for name in manifest['protected_files']:
            key = PREFIX + SKIN + '/' + name
            if key in changes:
                manifest['protected_files'][name] = sha(changes[key])
        changes[PREFIX + SKIN + '/Infinity-Protected-Manifest.json'] = (json.dumps(manifest, indent=2, sort_keys=True) + '\n').encode()
        plan = {n: {'before': sha(archive.read(n)), 'after': sha(raw)} for n, raw in changes.items()}
        assert all(row['before'] != row['after'] for row in plan.values())
        for name, row in plan.items():
            assert authority['payload']['member:' + name] == {'owner':'INFINITY','sha256':row['before']}, name
        # Explicit plans, not broad path allowlists, bind every packaged member.
        pin = HERE / 'SOURCE-PLAN.json'
        if pin.exists(): assert json.loads(pin.read_text()) == plan, 'Reviewed source plan differs'
        for name, raw in changes.items():
            target = out / 'members' / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
    save(out / 'SOURCE-PLAN.json', plan)
    save(out / 'STAGE.json', dict(input_sha256=scope['input_apk_sha256'], module=module,
         manifest_sha256=sha(new_manifest), changed_members=len(changes),
         nonselected_functions_byte_exact=functions, original75_source_files_authenticated=True,
         preserved2103426_optimizations=True, native_DEX_Cobra_shutdown='BYTE_IDENTICAL_NO_EDIT',
         APK_produced=False, module_signature='ORIGINAL_SIGNER_REQUIRED'))
    return out


if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--baseline', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    generate(**vars(p.parse_args()))
